"""Validation utilities for a SYNTHETIC spectroscopy optimisation portfolio.

All benchmark samples are generated by the illustrative simulator; this module
makes no assertion about physical MOF films or real instrument behaviour.
"""
from __future__ import annotations
import argparse
import csv
import json
import hashlib
from pathlib import Path
import numpy as np
from autolab import BOUNDS, WAVELENGTHS, evaluate, make_spectra, features, next_point

INITIAL = np.array([[.25,.2],[.95,.2],[.25,.8],[.95,.8],[.6,.5]])


def repeated_measurement(concentration: float, flow: float, *, seed: int=42, repeats: int=5) -> dict:
    """Separate noisy simulator evaluations at fixed settings (not real repeats)."""
    if repeats < 2:
        raise ValueError('repeats must be >=2')
    rng = np.random.default_rng(seed)
    values = [evaluate((concentration,flow),rng)[0] for _ in range(repeats)]
    return {'repeats':repeats,'mean':float(np.mean(values)),
            'sample_std':float(np.std(values,ddof=1)),
            'standard_error':float(np.std(values,ddof=1)/np.sqrt(repeats)),
            'values':[float(v) for v in values]}


def load_spectrum_csv(path: Path) -> dict:
    """Read one timepoint of paired polarisation spectra, with explicit units.

    Columns: wavelength_nm,parallel_absorbance,perpendicular_absorbance.
    Requires complete monotonic sampling; no automatic extrapolation.
    """
    with Path(path).open(newline='') as f:
        reader=csv.DictReader(f)
        expected={'wavelength_nm','parallel_absorbance','perpendicular_absorbance'}
        if not expected.issubset(reader.fieldnames or []):
            raise ValueError('CSV must contain '+', '.join(sorted(expected)))
        rows=list(reader)
    if len(rows)<10:
        raise ValueError('At least 10 wavelength rows required')
    arr=np.array([[float(r['wavelength_nm']),float(r['parallel_absorbance']),
                   float(r['perpendicular_absorbance'])] for r in rows])
    if not np.isfinite(arr).all() or not np.all(np.diff(arr[:,0])>0):
        raise ValueError('Wavelengths must increase and values must be finite')
    if (arr[:,1:]<0).any():
        raise ValueError('Absorbances must be nonnegative')
    return {'wavelength_nm':arr[:,0],'parallel_absorbance':arr[:,1],
            'perpendicular_absorbance':arr[:,2]}


def csv_spectrum_features(path: Path) -> dict:
    """Baseline estimated from the uppermost 8% wavelength window."""
    d=load_spectrum_csv(path)
    wl=d['wavelength_nm']; p=d['parallel_absorbance']; s=d['perpendicular_absorbance']
    tail=max(3,int(np.ceil(.08*len(wl))))
    p=np.maximum(p-np.median(p[-tail:]),0)
    s=np.maximum(s-np.median(s[-tail:]),0)
    idx=int(np.argmax((p+s)/2))
    return {'peak_nm':float(wl[idx]),
            'mean_peak_absorbance':float((p[idx]+s[idx])/2),
            'polarization_contrast':float((p[idx]-s[idx])/(p[idx]+s[idx]+1e-12))}


def export_example_csv(path: Path,seed: int=42) -> None:
    p,s=make_spectra(.7,.4,np.random.default_rng(seed))
    path.parent.mkdir(parents=True,exist_ok=True)
    with path.open('w',newline='') as f:
        writer=csv.writer(f)
        writer.writerow(['wavelength_nm','parallel_absorbance','perpendicular_absorbance'])
        writer.writerows(zip(WAVELENGTHS,p[-1],s[-1]))


def seeded_simulation(point, run_seed):
    """Common-random-numbers scheme: same point and run means same simulated noise."""
    coords=np.asarray(point,dtype='<f8').tobytes()
    digest=hashlib.sha256(str(run_seed).encode()+coords).digest()
    point_seed=int.from_bytes(digest[:8], 'little')
    return evaluate(point,np.random.default_rng(point_seed))[0]


def benchmark(seed: int=42, runs: int=5, steps: int=12, bootstrap_samples: int=2000) -> dict:
    """Paired seeded BO vs uniform random experiment choice, same 5 initial points.

    Each policy gets its own noise draw. Results are illustrative and finite-budget.
    """
    if bootstrap_samples < 100:
        raise ValueError('bootstrap_samples must be >=100')
    if runs<2 or steps<6:
        raise ValueError('runs >=2 and steps >=6 required')
    traces={'bayesian':[],'random':[]}
    for k in range(runs):
        for policy in traces:
            rng=np.random.default_rng(seed+100*k+(0 if policy=='bayesian' else 10000))
            x=[];y=[];trace=[]
            for t in range(steps):
                if t<5:
                    point=INITIAL[t]
                elif policy=='bayesian':
                    point=next_point(x,y,rng,candidates=500)
                else:
                    point=BOUNDS[:,0]+rng.random(2)*(BOUNDS[:,1]-BOUNDS[:,0])
                score=seeded_simulation(point, seed+100*k)
                x.append(list(point));y.append(score);trace.append(float(max(y)))
            traces[policy].append(trace)
    bo=np.array(traces['bayesian']);ran=np.array(traces['random'])
    diffs=bo[:,-1]-ran[:,-1]
    # Paired bootstrap CI quantifies run-to-run variation in the *toy simulator*.
    bootrng=np.random.default_rng(seed+991733)
    indices=bootrng.integers(0,runs,size=(bootstrap_samples,runs))
    bootmeans=diffs[indices].mean(axis=1)
    ci=np.quantile(bootmeans,[.025,.975])
    return {'data_type':'entirely simulated; no real spectra or hardware',
            'seed':seed,'runs':runs,'experiments_per_run':steps,'initial_settings':5,'noise_scheme':'common deterministic point-wise simulator noise within each run',
            'bayesian_final_mean':float(bo[:,-1].mean()),
            'random_final_mean':float(ran[:,-1].mean()),
            'paired_final_differences':diffs.tolist(),
            'mean_paired_difference':float(diffs.mean()),
            'bo_wins':int((diffs>0).sum()),
            'mean_difference_bootstrap_95pct_ci':[float(ci[0]),float(ci[1])],
            'bootstrap_samples':bootstrap_samples,
            'paired_difference_sample_sd':float(np.std(diffs,ddof=1)),
            'all_methods_share_initial_settings':True,
            'interpretation':'Small-sample synthetic comparison only; not proof of superiority',
            'traces':{key:[list(map(float,row)) for row in value] for key,value in traces.items()}}


def main():
    ap=argparse.ArgumentParser(description='Synthetic workflow validation')
    ap.add_argument('--output',type=Path,default=Path('results'))
    ap.add_argument('--runs',type=int,default=5)
    ap.add_argument('--steps',type=int,default=12)
    ap.add_argument('--seed',type=int,default=42)
    ap.add_argument('--bootstrap-samples',type=int,default=2000)
    args=ap.parse_args()
    args.output.mkdir(exist_ok=True,parents=True)
    export_example_csv(args.output/'example_synthetic_spectrum.csv',seed=args.seed)
    feats=csv_spectrum_features(args.output/'example_synthetic_spectrum.csv')
    (args.output/'imported_features.json').write_text(json.dumps(feats,indent=2)+'\n')
    repeated=repeated_measurement(.7,.4,seed=args.seed)
    (args.output/'repeatability.json').write_text(json.dumps(repeated,indent=2)+'\n')
    result=benchmark(seed=args.seed,runs=args.runs,steps=args.steps,bootstrap_samples=args.bootstrap_samples)
    (args.output/'benchmark.json').write_text(json.dumps(result,indent=2)+'\n')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig,ax=plt.subplots(figsize=(8,4.8))
    for policy,label in [('bayesian','Gaussian process + expected improvement'),('random','Uniform random')]:
        arr=np.array(result['traces'][policy]);n=np.arange(1,arr.shape[1]+1)
        ax.plot(n,arr.mean(axis=0),label=label)
        ax.fill_between(n,arr.min(axis=0),arr.max(axis=0),alpha=.12)
    ax.set(xlabel='Simulated experiment number',ylabel='Best synthetic objective (mean across runs)',
           title='Synthetic benchmark: mean with min–max band')
    ax.legend();fig.tight_layout();fig.savefig(args.output/'benchmark.png',dpi=150);plt.close(fig)
    print(json.dumps({k:v for k,v in result.items() if k!='traces'},indent=2))

if __name__=='__main__':
    main()
